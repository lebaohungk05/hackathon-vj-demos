def build():
    data, seen = {}, set()
    for en, ja, vi in S:
        if en in seen and data[en] != {"ja": ja, "vi": vi}:
            raise SystemExit(f"conflicting duplicate key: {en}")
        seen.add(en)
        data[en] = {"ja": ja, "vi": vi}
    return data


def write(data):
    body = json.dumps(data, ensure_ascii=False, indent=1, sort_keys=True)
    (ROOT / "ui" / "strings.js").write_text("window.UI_STRINGS = " + body + ";\n", encoding="utf-8")


if __name__ == "__main__":
    d = build()
    write(d)
    print(len(d), "UI strings")
